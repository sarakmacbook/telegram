#!/usr/bin/env node
/**
 * Bundles index.html into src/generated/widget-html.mjs so a serverless
 * function does not have to read it from disk, and checks Telegram's widget
 * limits while doing it.
 *
 *   npm run build            generate the module
 *   npm run check            validate only (also used before a deploy)
 */

import { existsSync } from 'node:fs';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { validateWidgetHtml, compressedSize } from '../src/widget.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'src', 'generated', 'widget-html.mjs');
// Vercel requires a non-empty output directory when a buildCommand is
// configured. The app itself is functions-first, so the only static asset is a
// crawl policy; API routes and the rewritten root remain handled by functions.
const PUBLIC_OUT = path.join(ROOT, 'public');
const ROBOTS_FILE = path.join(PUBLIC_OUT, 'robots.txt');
const ROBOTS_CONTENT = 'User-agent: *\nDisallow: /\n';
const CHECK = process.argv.includes('--check');
const widgetPath = process.env.WIDGET_PATH || 'index.html';

function fail(message) {
  process.stderr.write(`✖ ${message}\n`);
  process.exitCode = 1;
}

const html = await readFile(path.resolve(ROOT, widgetPath), 'utf8');
const report = validateWidgetHtml(html);

process.stdout.write(
  [
    `widget   ${widgetPath}`,
    `raw      ${report.rawBytes} / 32768 bytes`,
    `zlib-9   ${report.compressedBytes} / 4096 bytes (${Math.round((report.compressedBytes / 4096) * 100)}% of the budget)`,
    '',
  ].join('\n'),
);
for (const warning of report.warnings) process.stdout.write(`warn     ${warning}\n`);
for (const error of report.errors) fail(error);
if (report.errors.length) process.exit(1);

if (CHECK) {
  if (!existsSync(PUBLIC_OUT) || !existsSync(ROBOTS_FILE)) {
    fail('public/robots.txt is missing — run `npm run build`');
    process.exit(1);
  }
  const robots = await readFile(ROBOTS_FILE, 'utf8');
  if (robots !== ROBOTS_CONTENT) {
    fail('public/robots.txt is stale — run `npm run build`');
    process.exit(1);
  }
  let existing = null;
  try {
    existing = await readFile(OUT, 'utf8');
  } catch {
    fail(`${path.relative(ROOT, OUT)} is missing — run \`npm run build\``);
    process.exit(1);
  }
  const expected = JSON.stringify(html);
  if (!existing.includes(expected)) {
    fail(`${path.relative(ROOT, OUT)} is stale — run \`npm run build\``);
    process.exit(1);
  }
  process.stdout.write('ok       bundle is up to date\n');
  process.exit(0);
}

await mkdir(PUBLIC_OUT, { recursive: true });
await writeFile(ROBOTS_FILE, ROBOTS_CONTENT, 'utf8');
process.stdout.write(`ok       wrote ${path.relative(ROOT, ROBOTS_FILE)} (non-empty Vercel output)\n`);
await mkdir(path.dirname(OUT), { recursive: true });
const module = `// Generated by scripts/build-widget.mjs from ${widgetPath} — do not edit by hand.
// Rebuild with \`npm run build\`; \`npm run check\` fails when this file is stale.
export const widgetHtml = ${JSON.stringify(html)};

export const widgetMeta = ${JSON.stringify(
  {
    source: widgetPath,
    rawBytes: report.rawBytes,
    compressedBytes: report.compressedBytes,
    compressedLimit: 4096,
    builtAt: new Date().toISOString(),
  },
  null,
  2,
)};

export default widgetHtml;
`;

await writeFile(OUT, module, 'utf8');
process.stdout.write(
  `ok       wrote ${path.relative(ROOT, OUT)} (${module.length} bytes, html ${compressedSize(html)} bytes compressed)\n`,
);
